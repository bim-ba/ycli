def _snake(name: str) -> str:
    """``WorkbookExport`` -> ``workbook_export``."""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).lower()


def _pascal(name: str) -> str:
    """``created_by`` -> ``CreatedBy``; ``revId`` -> ``RevId``."""
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", name))


# Where a schema holds other schemas: under a name each, in a list, or as one value.
_NAMED = ("properties", "patternProperties", "$defs")
_LISTED = ("oneOf", "anyOf", "allOf", "prefixItems")
_SINGLE = ("items", "additionalProperties", "not")


def _children(schema: dict[str, Any]) -> Iterator[tuple[str, dict[str, Any], Any, Any]]:
    """The schemas directly inside ``schema``: a name suffix, the child, its holder and key."""
    for keyword in _NAMED:
        for name, child in schema.get(keyword, {}).items():
            if isinstance(child, dict):
                yield _pascal(name), child, schema[keyword], name
    for keyword in _LISTED:
        for index, child in enumerate(schema.get(keyword, [])):
            if isinstance(child, dict):
                yield f"Variant{index + 1}", child, schema[keyword], index
    for keyword, suffix in zip(_SINGLE, ("Item", "Value", "Not"), strict=True):
        if isinstance(schema.get(keyword), dict):
            yield suffix, schema[keyword], schema, keyword


def _schemas(schema: dict[str, Any]) -> Iterator[dict[str, Any]]:
    """``schema`` and every schema inside it; a map of property names is not one."""
    yield schema
    for _, child, _, _ in _children(schema):
        yield from _schemas(child)


def _bodies(spec: dict[str, Any]) -> Iterator[tuple[str, str, str, dict[str, Any]]]:
    """Each operation's request and reply: name, section, ``Request``/``Response``, holder."""
    for path, item in spec["paths"].items():
        operation = item["post"]
        (tag,) = operation["tags"]
        body = operation.get("requestBody", {}).get("content", {}).get("application/json")
        reply = operation["responses"]["200"].get("content", {}).get("application/json")
        for holder, kind in ((body, "Request"), (reply, "Response")):
            if holder and holder.get("schema"):  # no body, or `{}`: untyped stays untyped
                yield path.rsplit("/", 1)[1], tag, kind, holder


def _every_schema(spec: dict[str, Any]) -> Iterator[dict[str, Any]]:
    for schema in spec["components"]["schemas"].values():
        yield from _schemas(schema)
    for _, _, _, holder in _bodies(spec):
        yield from _schemas(holder["schema"])


def _target(spec: dict[str, Any], schema: dict[str, Any]) -> dict[str, Any] | None:
    """The component ``schema`` refers to, or ``schema`` itself when it is written in place."""
    ref = schema.get("$ref")
    if not isinstance(ref, str):
        return schema
    return spec["components"]["schemas"].get(ref.removeprefix(_REF))


