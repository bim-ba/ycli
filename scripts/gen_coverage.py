@dataclass(frozen=True)
class DomainSpec:
    """One domain to document: its heading, CLI/MCP namespace slug, live client, and groups."""

    title: str
    slug: str
    client: object
    categories: list[tuple[str, list[str]]]


@dataclass(frozen=True)
class ResourceRow:
    """A single table row: a resource, its wrapped ops, and per-surface reachability.

    ``resource_url`` links the resource name (``None`` → plain text). ``operation_urls`` is
    the final link target per operation — its own endpoint page, else the resource page as a
    fallback, else ``None`` (plain text). ``operation_specific[i]`` is ``True`` when operation
    ``i`` had a dedicated page (vs. falling back to the resource link); it drives the gap stats.
    ``operation_gaps[i]`` is the anchor of the row that says how operation ``i`` differs from
    the published API, or ``None`` when it does not (the operation is covered).
    """

    display: str
    operations: tuple[str, ...]
    has_cli: bool
    has_mcp: bool
    resource_url: str | None
    operation_urls: tuple[str | None, ...]
    operation_specific: tuple[bool, ...]
    operation_gaps: tuple[str | None, ...] = ()


@dataclass(frozen=True)
class DomainReport:
    """A rendered domain: its category groups (each a list of rows) plus headline totals."""

    title: str
    slug: str
    groups: list[tuple[str, list[ResourceRow]]]
    resource_count: int
    operation_count: int
    mcp_tool_count: int


@dataclass(frozen=True)
class LinkStats:
    """How the doc-link map covers the tables, and which items have no public link at all.

    ``gaps`` lists the ``<domain>.<resource>[.<operation>]`` identifiers rendered as plain text
    (no known URL) so the shortfall is explicit, not silent.
    """

    resources: int
    linked_resources: int
    operations: int
    specific_ops: int
    fallback_ops: int
    plain_ops: int
    gaps: tuple[str, ...]


def _cli_paths() -> list[str]:
    """Every CLI command path (space-joined), via the shared surface enumerator."""
    return cli_tree()


def _mcp_tool_names() -> list[str]:
    """Every MCP tool name, from the committed signature snapshot (``name(params)`` lines)."""
    lines = MCP_SIGNATURES.read_text(encoding="utf-8").splitlines()
    return [line.split("(", 1)[0] for line in lines]


def _display_name(attribute: str) -> str:
    """Resource attribute → its CLI/MCP/display name (``import_`` → ``import``)."""
    return attribute[:-1] if attribute.endswith("_") else attribute


def _sdk_operations(resource: object) -> tuple[str, ...]:
    """Public op names defined on the resource client class itself, in source order.

    Dunder and leading-underscore internals do not count.
    """
    ops: list[str] = []
    for name, member in type(resource).__dict__.items():
        if name.startswith("_"):
            continue
        if inspect.isfunction(member):
            ops.append(name)
    return tuple(ops)


def _cli_ops(slug: str, display: str, paths: list[str]) -> list[str]:
    """CLI sub-command remainders under ``<slug> <display>`` (segment-exact prefix match)."""
    prefix = [slug, display]
    return [" ".join(s[2:]) for path in paths if (s := path.split())[:2] == prefix and len(s) > 2]


def _mcp_tools(slug: str, display: str, tools: list[str]) -> list[str]:
    """MCP tool names under the ``<slug>_<display>_`` namespace."""
    prefix = f"{slug}_{display}_"
    return [tool for tool in tools if tool.startswith(prefix)]


def _snapshot_links(service: str) -> dict[str, dict]:
    """The link map of a service whose snapshot holds each operation's reference page.

    An SDK operation links to the page of the operation it sends; its resource links to the
    section those pages lie in. An operation without a page stays plain text.
    """
    pages = {found.path: found.page for found in api_surface.load(service) if found.page}
    links: dict[str, dict] = {}
    for call in api_drift.calls():
        domain, resource, operation = call.operation.split(".")
        page = pages.get(call.path)
        if domain == service and page:
            entry = links.setdefault(_display_name(resource), {"operations": {}})
            entry["operations"][operation] = page
            entry["resource"] = page.rpartition("/")[0] + "/"
    return links


def _load_link_map() -> dict[str, dict[str, dict]]:
    """The doc-link map, keyed ``domain → resource → {resource, operations}``.

    Committed for the services whose pages are found by hand (``coverage_urls.toml``); read
    from the snapshot for DataLens, whose refresh lists the pages there are.
    """
    committed = tomllib.loads(COVERAGE_URLS.read_text(encoding="utf-8"))
    return {**committed, "datalens": _snapshot_links("datalens")}


def _doc_url(slug: str, path: str) -> str:
    """A relative api-ref ``path`` → its absolute public Yandex documentation URL."""
    return API_DOCS[slug].format(path=path)


def _link(text: str, url: str | None) -> str:
    """``text`` as a Markdown link to ``url``, or bare ``text`` when there is no URL."""
    return f"[{text}]({url})" if url else text


def _make_row(
    slug: str,
    attribute: str,
    resource: object,
    urls: dict[str, dict],
    paths: list[str],
    tools: list[str],
    gaps: Mapping[str, str],
) -> ResourceRow:
    """Assemble one :class:`ResourceRow`, resolving each op to its page / resource / plain text."""
    display = _display_name(attribute)
    operations = _sdk_operations(resource)
    entry = urls.get(display, {})
    resource_path = entry.get("resource")
    operation_paths = entry.get("operations", {})
    operation_urls: list[str | None] = []
    operation_specific: list[bool] = []
    for operation in operations:
        own = operation_paths.get(operation)
        operation_specific.append(own is not None)
        target = own or resource_path
        operation_urls.append(_doc_url(slug, target) if target else None)
    return ResourceRow(
        display=display,
        operations=operations,
        has_cli=bool(_cli_ops(slug, display, paths)),
        has_mcp=bool(_mcp_tools(slug, display, tools)),
        resource_url=_doc_url(slug, resource_path) if resource_path else None,
        operation_urls=tuple(operation_urls),
        operation_specific=tuple(operation_specific),
        operation_gaps=tuple(gaps.get(f"{slug}.{attribute}.{name}") for name in operations),
    )


def _report(
    spec: DomainSpec,
    paths: list[str],
    tools: list[str],
    urls: dict[str, dict],
    gaps: Mapping[str, str],
) -> DomainReport:
    """Build a fully-computed :class:`DomainReport` from a live client + surface + link data."""
    discovered = {name for name, value in vars(spec.client).items() if isinstance(value, Resource)}
    placed: set[str] = set()
    groups: list[tuple[str, list[ResourceRow]]] = []
    operation_count = 0

    for heading, attributes in spec.categories:
        rows: list[ResourceRow] = []
        for attribute in attributes:
            resource = getattr(spec.client, attribute)
            if not isinstance(resource, Resource):
                raise SystemExit(f"gen_coverage: {spec.slug}.{attribute} is not a resource client")
            placed.add(attribute)
            row = _make_row(spec.slug, attribute, resource, urls, paths, tools, gaps)
            if not row.operations:
                raise SystemExit(f"gen_coverage: {spec.slug}.{attribute} exposes no SDK operations")
            operation_count += len(row.operations)
            rows.append(row)
        groups.append((heading, rows))

    unplaced = sorted(discovered - placed)
    if unplaced:
        rows = []
        for attribute in unplaced:
            resource = getattr(spec.client, attribute)
            row = _make_row(spec.slug, attribute, resource, urls, paths, tools, gaps)
            operation_count += len(row.operations)
            rows.append(row)
        groups.append(("Other", rows))

    return DomainReport(
        title=spec.title,
        slug=spec.slug,
        groups=groups,
        resource_count=len(discovered),
        operation_count=operation_count,
        mcp_tool_count=sum(1 for tool in tools if tool.startswith(f"{spec.slug}_")),
    )


def link_stats(reports: list[DomainReport]) -> LinkStats:
    """Aggregate doc-link coverage across ``reports`` (own page vs. resource fallback vs. none)."""
    resources = linked_resources = 0
    operations = specific = fallback = plain = 0
    gaps: list[str] = []
    for report in reports:
        for _heading, rows in report.groups:
            for row in rows:
                resources += 1
                identifier = f"{report.slug}.{row.display}"
                if row.resource_url:
                    linked_resources += 1
                else:
                    gaps.append(identifier)
                for operation, url, own in zip(
                    row.operations, row.operation_urls, row.operation_specific, strict=True
                ):
                    operations += 1
                    if own:
                        specific += 1
                    elif url:
                        fallback += 1
                    else:
                        plain += 1
                        gaps.append(f"{identifier}.{operation}")
    return LinkStats(
        resources=resources,
        linked_resources=linked_resources,
        operations=operations,
        specific_ops=specific,
        fallback_ops=fallback,
        plain_ops=plain,
        gaps=tuple(sorted(gaps)),
    )


def _render_table(rows: list[ResourceRow]) -> list[str]:
    """The Markdown lines for one resource-group table.

    Every row comes from an SDK resource, so the table has no SDK column: it would always be
    ticked.
    """
    lines = [
        "| Resource | Operations | CLI | MCP |",
        "|----------|------------|:---:|:---:|",
    ]
    for row in rows:
        gaps = row.operation_gaps or (None,) * len(row.operations)
        cells = zip(row.operations, row.operation_urls, gaps, strict=True)
        operations = " · ".join(
            _link(operation, url) + (f" [{PARTIAL}](#{gap})" if gap else "")
            for operation, url, gap in cells
        )
        cli = YES if row.has_cli else NO
        mcp = YES if row.has_mcp else NO
        lines.append(f"| {_link(row.display, row.resource_url)} | {operations} | {cli} | {mcp} |")
    return lines


@dataclass(frozen=True)
class Totals:
    """The headline numbers: operations, resources and every registered MCP tool."""

    operations: int
    resources: int
    mcp_tools: int
    domain_mcp_tools: int
    cross_cutting_tools: tuple[str, ...]


def _totals(reports: list[DomainReport]) -> Totals:
    """Sum the domains, adding the MCP tools that belong to no domain (``status_get``)."""
    domain_prefixes = tuple(f"{report.slug}_" for report in reports)
    cross_cutting = tuple(
        tool for tool in _mcp_tool_names() if not tool.startswith(domain_prefixes)
    )
    domain_mcp_tools = sum(report.mcp_tool_count for report in reports)
    return Totals(
        operations=sum(report.operation_count for report in reports),
        resources=sum(report.resource_count for report in reports),
        mcp_tools=domain_mcp_tools + len(cross_cutting),
        domain_mcp_tools=domain_mcp_tools,
        cross_cutting_tools=cross_cutting,
    )


def _listed(names: list[str]) -> str:
    """``["Tracker", "Wiki", "Forms"]`` -> ``"Tracker, Wiki, and Forms"``."""
    return ", ".join(names[:-1]) + f", and {names[-1]}"


def _render_not_covered(drift: api_drift.Drift) -> list[str]:
    """The published operations of a service that ycli does not wrap, each with its reason."""
    reasons = dict(drift.excluded)
    missing = [*drift.not_wrapped, *reasons]
    if not missing:
        return []
    lines = ["", f"**Not covered** ({len(missing)})", ""]
    for operation in missing:
        why = reasons.get(operation)
        published = _published(drift.service, operation)
        lines.append(f"- {NOT_COVERED} {published}" + (f": {why}" if why else ""))
    return lines


def _render(reports: list[DomainReport], found: tuple[api_drift.Drift, ...]) -> str:
    """The full inner Markdown block (without the surrounding markers)."""
    drifts = {drift.service: drift for drift in found}
    totals = _totals(reports)
    cross_cutting_names = ", ".join(f"`{tool}`" for tool in sorted(totals.cross_cutting_tools))
    stats = link_stats(reports)

    lines = [
        "## Coverage",
        "",
        f'<img src="{COVERAGE_SVG_URL}" alt="{totals.operations} operations across '
        f"{totals.resources} resources: "
        + ", ".join(f"{report.title} {report.operation_count}" for report in reports)
        + '" width="760">',
        "",
        f"`ycli` wraps **{totals.operations} operations across {totals.resources} resources** of "
        f"the {_listed([report.title for report in reports])} API. Every one is reachable "
        "from the **Python SDK** "
        f"and the **CLI**, and {totals.mcp_tools} **MCP** tools serve them to agents "
        f"({totals.domain_mcp_tools} per service plus {cross_cutting_names}).",
        "",
        f"> **Legend.** {YES} in **CLI** or **MCP** means the resource is reachable on that "
        "surface; MCP tools carry honest hints (reads are `readOnlyHint`, writes say whether "
        "they are destructive or idempotent), and `ycli mcp start --read-only` serves only the "
        "reads. Resource and operation names link to the official **Yandex API reference**. "
        "An operation has one of three states against what Yandex publishes. **Covered** (no "
        "mark): ycli sends every published parameter and reads every published field. "
        f"**Partial** ({PARTIAL}): ycli wraps it and differs somewhere; the mark links to the "
        f"row that says where and why. **Not covered** ({NOT_COVERED}): Yandex publishes it "
        "and ycli does not wrap it; these are listed under each service. Wiki, Forms and "
        "DataLens are measured against their OpenAPI documents; Tracker publishes none, so "
        "its state is measured against the reference pages (operations, and query parameters "
        "where a page lists them). DataLens is in progress, wrapped section by section: the "
        "operations of a section ycli has not begun are pending, not missing. Generated from "
        "the code by "
        "[`scripts/gen_coverage.py`](scripts/gen_coverage.py); do not edit by hand.",
    ]
    for report in reports:
        lines += [
            "",
            f"### {report.title}",
            "",
            "<details>",
            f"<summary><b>{report.resource_count} resources · {report.operation_count} "
            f"operations · {report.mcp_tool_count} MCP tools</b></summary>",
        ]
        for heading, rows in report.groups:
            lines += ["", f"**{heading}**", "", *_render_table(rows)]
        lines += [*_render_not_covered(drifts[report.slug]), "", "</details>"]

    gaps = ", ".join(f"`{gap}`" for gap in stats.gaps)
    unlinked = (
        f" No public API reference exists yet for {gaps}, shown as plain text."
        if stats.gaps
        else ""
    )
    lines += [
        "",
        f"Every resource and operation above deep-links to the Yandex API reference: "
        f"{stats.specific_ops} of {stats.operations} operations resolve to their own endpoint "
        f"page and {stats.fallback_ops} to their resource's page.{unlinked} "
        "See `CONTRIBUTING.md` for the intentional exclusions (UI-only endpoints with no public "
        "REST API) and per-method notes.",
    ]
    return "\n".join([*lines, "", *_render_drift(found)])


