def _names(names: tuple[str, ...]) -> str:
    return ", ".join(f"`{name}`" for name in names)


def _published(service: str, operation: api_surface.Operation) -> str:
    """A published operation as ``METHOD /path``, linked to its reference page if it has one."""
    label = f"`{operation.method} {operation.path}`"
    return _link(label, REFERENCE[service] + operation.page if operation.page else None)


def _sdk(operations: tuple[str, ...]) -> str:
    """SDK operations without their service: ``wiki.pages.get`` → ``pages.get``."""
    return ", ".join(f"`{operation.split('.', 1)[1]}`" for operation in operations)


def _bodies(drift: api_drift.Drift) -> str:
    """How many published request bodies were compared: the rest have no typed model in ycli."""
    if not drift.bodies_published:
        return NO
    return f"{drift.bodies_compared} of {drift.bodies_published}"


